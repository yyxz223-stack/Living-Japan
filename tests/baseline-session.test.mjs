import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { EventEmitter } from 'node:events';
import { loadBaseline } from '../src/baseline.js';
import { createSession } from '../src/session.js';
import { createUserStore } from '../src/storage.js';

test('session startup normalizes in memory without writing the user transport', async () => {
  const root = new URL('../', import.meta.url);
  const { engine } = await loadBaseline(root, { fetcher: async url => ({ ok: true, json: async () => JSON.parse(await fs.readFile(url, 'utf8')) }) });
  let remote = null;
  let writes = 0;
  const transport = { read: async () => structuredClone(remote), write: async value => { writes += 1; remote = structuredClone(value); } };
  const store = createUserStore({ transport });
  await store.load();
  const session = createSession({ engine, store });
  await session.start();
  assert.equal(writes, 0);
  assert.equal(store.read().revision, 0);
  assert.deepEqual(await session.runtime.readSettings(), engine.normalizeSettings({}));
  const secondStore = createUserStore({ transport });
  await secondStore.load();
  const secondSession = createSession({ engine, store: secondStore });
  await secondSession.start();
  assert.equal(writes, 0);
  await session.runtime.saveSettings({ masterEnabled: false });
  assert.equal(writes, 1);
  assert.equal(remote.livingJapanSettings.masterEnabled, false);
  session.stop();
  secondSession.stop();
});

test('native session keeps request draws, recomputes saved text, isolates preview and cleans listeners', async () => {
  const root = new URL('../', import.meta.url);
  const { engine, data } = await loadBaseline(root, { fetcher: async url => ({ ok: true, json: async () => JSON.parse(await fs.readFile(url, 'utf8')) }) });
  const calls = [];
  const run = engine.runEngine;
  engine.runEngine = (messages, settings, options) => { calls.push(options); return run(messages, settings, { ...options, random: () => 0 }); };
  let saved = { livingJapanSettings: data.defaultSettings, livingJapanTextOverrides: engine.emptyTextOverrides(), customSlots: {} };
  const store = { read: () => structuredClone(saved), update: async mutate => { const next = structuredClone(saved); saved = mutate(next) || next; return structuredClone(saved); } };
  const eventSource = new EventEmitter();
  const macros = new Map();
  const context = { chat: [{ role: 'user', message: '新宿站。新宿御苑。' }], eventSource, registerMacro: (name, handler) => macros.set(name, handler), unregisterMacro: name => macros.delete(name) };
  const session = createSession({ engine, store, context });
  await session.start();
  assert.equal(eventSource.listenerCount('GENERATION_AFTER_COMMANDS'), 1);
  eventSource.emit('GENERATION_AFTER_COMMANDS', 'normal', {}, false);
  const first = macros.get('livingjapan')();
  assert.equal(typeof first, 'string');
  assert.equal(macros.get('livingjapan')(), first);
  assert.equal(calls[0].parentStationSelectionCache, calls[1].parentStationSelectionCache);
  assert.equal(calls[0].interestSelectionCache, calls[1].interestSelectionCache);
  assert.notEqual(calls[0].parentStationSelectionCache, calls[0].interestSelectionCache);
  await session.runtime.saveTextOverride('LJ_PLACE_STATION_SHINJUKU', null, '保存后的独立新宿站正文。');
  assert.match(macros.get('livingjapan')(), /保存后的独立新宿站正文/);
  assert.equal(calls[0].parentStationSelectionCache, calls[2].parentStationSelectionCache);
  await session.preview();
  assert.notEqual(calls[0].parentStationSelectionCache, calls[3].parentStationSelectionCache);
  assert.notEqual(calls[0].interestSelectionCache, calls[3].interestSelectionCache);
  eventSource.emit('GENERATION_ENDED');
  eventSource.emit('GENERATION_AFTER_COMMANDS', 'normal', {}, false);
  macros.get('livingjapan')();
  assert.notEqual(calls[0].parentStationSelectionCache, calls[4].parentStationSelectionCache);
  await session.runtime.saveSettings({ ...saved.livingJapanSettings, masterEnabled: false });
  assert.equal(macros.get('livingjapan')(), '');
  const input = { tagName: 'TEXTAREA', value: '原有输入', dispatchEvent() {} };
  const doc = { getElementById: () => input };
  assert.equal(engine.appendPlaceNameToChatInput(doc, '东京站').ok, true);
  assert.equal(input.value, '原有输入东京站');
  assert.equal(engine.appendTrafficToChatInput(doc, '<!-- traffic info：测试路线 -->').ok, true);
  assert.match(input.value, /原有输入东京站\n<!-- traffic info：测试路线 -->/);
  session.stop();
  assert.equal(eventSource.listenerCount('GENERATION_AFTER_COMMANDS'), 0);
  assert.equal(macros.size, 0);
  const core = await fs.readFile(new URL('../src/legacy/engine.js', import.meta.url), 'utf8');
  assert.doesNotMatch(core, /function (?:createRuntime|buildPanelHtml|autoStart)|__LJ_UI_STYLE__/);
});
